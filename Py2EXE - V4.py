# ---------- Builder engine ----------
class BuilderEngine:
    def __init__(self, python_exe: str, log_queue: queue.Queue):
        self.python_exe = python_exe
        self.log_queue = log_queue
        self.proc: subprocess.Popen | None = None
        self.cancelled = False

    def _emit(self, text: str):
        try:
            self.log_queue.put(text)
        except Exception:
            pass

    def check_pyinstaller(self) -> str | None:
        try:
            out = subprocess.check_output(
                [self.python_exe, "-m", "PyInstaller", "--version"],
                stderr=subprocess.STDOUT,
                text=True,
                creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
            )
            return out.strip()
        except Exception:
            return None

    def install_pyinstaller(self) -> tuple[bool, str]:
        try:
            out = subprocess.check_output(
                [self.python_exe, "-m", "pip", "install", "--upgrade", "pip", "pyinstaller"],
                stderr=subprocess.STDOUT,
                text=True,
            )
            return True, out
        except subprocess.CalledProcessError as e:
            return False, e.output

    def build_one(self, spec: dict) -> tuple[bool, Path | None]:
        """
        spec keys:
          script_path, out_dir, onefile, console, name, icon, add_data(list of (src,dst)),
          hidden_imports(list), paths(list), clean(bool), upx(bool), upx_dir(opt), manifest(bool),
          dpiaware(bool), uac_admin(bool), version_meta(dict or None), extra_args(list),
          copy_to_temp(bool)
        """
        self.cancelled = False
        script_path = Path(spec["script_path"]).resolve()
        work_dir = script_path.parent

        # Optionally copy sources to temp
        if spec.get("copy_to_temp"):
            tmp_root = Path(tempfile.mkdtemp(prefix="py2exe_src_"))
            tmp_project = tmp_root / work_dir.name
            shutil.copytree(work_dir, tmp_project, dirs_exist_ok=True)
            script_rel = script_path.name
            script_path = tmp_project / script_rel
            work_dir = tmp_project

        args = [self.python_exe, "-m", "PyInstaller"]

        # quick options
        if spec.get("onefile", True):
            args.append("--onefile")
        if not spec.get("console", False):
            args.append("--noconsole")
        if spec.get("name"):
            args += ["--name", spec["name"]]
        if spec.get("icon"):
            args += ["--icon", spec["icon"]]
        if spec.get("out_dir"):
            args += ["--distpath", spec["out_dir"]]
        if spec.get("clean"):
            args.append("--clean")

        # resources (add-data)
        for src, dst in spec.get("add_data", []):
            if src:
                args += ["--add-data", f"{src};{dst or '.'}"]

        # hidden imports & paths
        for mod in spec.get("hidden_imports", []):
            if mod.strip():
                args += ["--hidden-import", mod.strip()]
        for p in spec.get("paths", []):
            if p.strip():
                args += ["--paths", p.strip()]

        # version info
        vf_tmp = None
        if spec.get("version_meta"):
            vf_tmp = make_version_file(spec["version_meta"])
            args += ["--version-file", vf_tmp]

        # manifest / uac / dpi
        mf_tmp = None
        if spec.get("manifest") or spec.get("uac_admin"):
            mf_tmp = make_manifest_file(bool(spec.get("dpiaware")), bool(spec.get("uac_admin")))
            args += ["--manifest", mf_tmp]
        if spec.get("uac_admin"):
            args.append("--uac-admin")

        # upx
        if spec.get("upx"):
            upx_dir = spec.get("upx_dir")
            if upx_dir and Path(upx_dir).exists():
                args += ["--upx-dir", upx_dir]

        # extra args
        for ea in spec.get("extra_args", []):
            if ea.strip():
                args.append(ea.strip())

        # finally, the script
        args.append(str(script_path))

        self._emit(f"\n=== Building: {script_path.name} ===\n")
        self._emit(" ".join(quote_win(a) for a in args) + "\n\n")

        try:
            self.proc = subprocess.Popen(
                args,
                cwd=str(work_dir),
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                bufsize=1,
            )
            assert self.proc.stdout
            for line in self.proc.stdout:
                if self.cancelled:
                    break
                self._emit(line)
            rc = self.proc.wait()
        except Exception as e:
            self._emit(f"\n[ERROR] {e}\n")
            rc = 1
        finally:
            self.proc = None
            try:
                if vf_tmp:
                    Path(vf_tmp).parent.rmdir()
            except Exception:
                pass
            try:
                if mf_tmp:
                    Path(mf_tmp).parent.rmdir()
            except Exception:
                pass

        if rc != 0:
            self._emit("\n[FAILED]\n")
            return False, None

        # Determine exe path
        dist = Path(spec["out_dir"]) if spec.get("out_dir") else (work_dir / "dist")
        exe_name = spec.get("name") or script_path.stem
        exe_path = (dist / f"{exe_name}.exe") if spec.get("onefile", True) else (dist / exe_name / f"{exe_name}.exe")
        self._emit(f"\n[SUCCESS] {exe_path}\n")
        return True, exe_path

    def cancel(self):
        self.cancelled = True
        if self.proc and self.proc.poll() is None:
            try:
                self.proc.terminate()
            except Exception:
                pass


# ---------- Tooltip ----------
class ToolTip:
    """Simple hover tooltip for Tkinter widgets with dark theme."""
    def __init__(self, widget, text: str, wrap: int = 56, delay_ms: int = 300):
        self.widget = widget
        self.text = text
        self.wrap = wrap
        self.delay_ms = delay_ms
        self.tipwin: tk.Toplevel | None = None
        self._after_id: str | None = None

        widget.bind("<Enter>", self._on_enter, add="+")
        widget.bind("<Leave>", self._on_leave, add="+")
        widget.bind("<Motion>", self._on_motion, add="+")
        widget.bind("<ButtonPress>", self._on_leave, add="+")

    def _on_enter(self, _):
        self._schedule()

    def _on_leave(self, _=None):
        self._cancel()
        self._hide()

    def _on_motion(self, e):
        if self.tipwin is not None:
            x = e.x_root + 14
            y = e.y_root + 18
            self.tipwin.geometry(f"+{x}+{y}")

    def _schedule(self):
        self._cancel()
        self._after_id = self.widget.after(self.delay_ms, self._show)

    def _cancel(self):
        if self._after_id:
            try:
                self.widget.after_cancel(self._after_id)
            except Exception:
                pass
            self._after_id = None

    def _show(self):
        if self.tipwin is not None:
            return
        self.tipwin = tw = tk.Toplevel(self.widget)
        tw.wm_overrideredirect(True)
        tw.attributes("-topmost", True)
        bg = "#0b1223"; fg = "#e5e7eb"; border = "#4b5563"
        frame = tk.Frame(tw, background=border, bd=0); frame.pack()
        inner = tk.Frame(frame, background=bg, bd=0); inner.pack(padx=1, pady=1)
        label = tk.Label(inner, text=self._wrap_text(self.text, self.wrap),
                         justify="left", background=bg, foreground=fg,
                         relief="flat", bd=0, padx=8, pady=6,
                         font=("Segoe UI", 9))
        label.pack()
        try:
            x = self.widget.winfo_pointerx() + 14
            y = self.widget.winfo_pointery() + 18
            tw.wm_geometry(f"+{x}+{y}")
        except Exception:
            pass

    def _hide(self):
        if self.tipwin is not None:
            try:
                self.tipwin.destroy()
            except Exception:
                pass
            self.tipwin = None

    @staticmethod
    def _wrap_text(text: str, width: int) -> str:
        import textwrap
        lines = []
        for para in text.splitlines():
            if not para.strip():
                lines.append("")
            else:
                lines.extend(textwrap.wrap(para, width=width))
        return "\n".join(lines)


def add_tip(widget, text: str):
    ToolTip(widget, text)



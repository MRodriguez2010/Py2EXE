# ---------- Settings storage ----------
CFG_DIR = Path(os.getenv("APPDATA", Path.home() / "AppData/Roaming")) / APP_ID
CFG_DIR.mkdir(parents=True, exist_ok=True)
CFG_FILE = CFG_DIR / "settings.json"


def load_settings() -> dict:
    try:
        return json.loads(CFG_FILE.read_text(encoding="utf-8"))
    except Exception:
        return {}


def save_settings(data: dict) -> None:
    try:
        CFG_FILE.write_text(json.dumps(data, indent=2), encoding="utf-8")
    except Exception:
        pass


# ---------- Utility helpers ----------
def default_python_exe() -> str:
    # Use current interpreter first; otherwise try common WindowsApps path
    if sys.executable:
        return sys.executable
    candidate = Path(os.getenv("LOCALAPPDATA", "")) / "Microsoft" / "WindowsApps" / "python3.11.exe"
    return str(candidate)


def quote_win(p: Path | str) -> str:
    s = str(p)
    if " " in s or ";" in s or "(" in s or ")" in s:
        return f'"{s}"'
    return s


def detect_upx_path() -> str | None:
    # Look for upx.exe in PATH
    for p in os.getenv("PATH", "").split(os.pathsep):
        exe = Path(p) / "upx.exe"
        if exe.exists():
            return str(exe.parent)
    return None


def make_version_file(meta: dict) -> str:
    """
    Create a temporary version file compatible with PyInstaller --version-file.
    meta keys: product, file_desc, company, version (e.g., "1.0.0")
    """
    def _tup(ver: str | None):
        ver = (ver or "1.0.0").split(".")
        ver += ["0"] * (4 - len(ver))
        return tuple(int(x) for x in ver[:4])

    contents = f"""
# UTF-8
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={_tup(meta.get('version'))},
    prodvers={_tup(meta.get('version'))},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        u'040904B0',
        [StringStruct(u'CompanyName', u'{meta.get('company','')}'),
         StringStruct(u'FileDescription', u'{meta.get('file_desc','')}'),
         StringStruct(u'FileVersion', u'{meta.get('version','1.0.0')}'),
         StringStruct(u'ProductName', u'{meta.get('product','')}'),
         StringStruct(u'ProductVersion', u'{meta.get('version','1.0.0')}')])
    ]),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
""".strip()
    tmp = Path(tempfile.mkdtemp(prefix="py2exe_meta_"))
    vf = tmp / "version_file.txt"
    vf.write_text(contents, encoding="utf-8")
    return str(vf)


